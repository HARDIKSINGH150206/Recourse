import type { Verdict } from "@recourse/shared";
import {
  SEMANTIC_CATEGORIES,
  lift,
  summarize,
  type CaseResult,
  type ConfigId,
  type Label,
  type Rate,
  type Summary,
} from "./metrics.js";

const ORDER: ConfigId[] = ["A1", "A2", "B", "C"];
const DESCRIPTION: Record<ConfigId, string> = {
  A1: "rules only, abstain when no rule is decisive",
  A2: "rules only, default to RELEASE",
  B: "rules + extractor + one judge",
  C: "full system: extractor + judge quorum + citation check",
};

export interface RunFile {
  run_id: string;
  config: {
    seed: number;
    generator_version: number;
    created_at: number;
    configs: ConfigId[];
    judges: number;
    headline_cases: number;
    controls: number;
    models: Verdict["models"];
    prompt_hash: string | null;
    settings_hash: string | null;
  };
  results: {
    configs: Partial<Record<ConfigId, Summary>>;
    lift: {
      ai: ConfigId;
      baseline: ConfigId;
      overall: ReturnType<typeof lift>;
      semantic: ReturnType<typeof lift>;
    }[];
  };
}

/**
 * Builds the run summary. Its `{ run_id, config, results }` shape is what `GET /bench/latest` serves
 * (apps/api), so it stays plain JSON.
 */
export function assembleRun(o: {
  runId: string;
  seed: number;
  generatorVersion: number;
  createdAt: number;
  judges: number;
  runs: Partial<Record<ConfigId, { results: CaseResult[]; verdicts: Verdict[] }>>;
}): RunFile {
  const configs = ORDER.filter((c) => o.runs[c]);
  const summaries: RunFile["results"]["configs"] = {};
  for (const c of configs) summaries[c] = summarize(o.runs[c]!.results);

  const verdicts = configs.flatMap((c) => o.runs[c]!.verdicts);
  const withModels = verdicts.find((v) => v.models.length > 0);
  const any = verdicts[0];
  const first = o.runs[configs[0]!]?.results ?? [];

  const pairs: [ConfigId, ConfigId][] = [
    ["B", "A1"],
    ["B", "A2"],
    ["C", "A1"],
    ["C", "A2"],
  ];
  return {
    run_id: o.runId,
    config: {
      seed: o.seed,
      generator_version: o.generatorVersion,
      created_at: o.createdAt,
      configs,
      judges: o.judges,
      headline_cases: first.filter((r) => !r.control).length,
      controls: first.filter((r) => r.control).length,
      models: withModels?.models ?? [],
      prompt_hash: any?.prompt_hash ?? null,
      settings_hash: any?.settings_hash ?? null,
    },
    results: {
      configs: summaries,
      lift: pairs.flatMap(([ai, baseline]) => {
        const a = summaries[ai];
        const b = summaries[baseline];
        return a && b
          ? [{ ai, baseline, overall: lift(a, b), semantic: lift(a, b, SEMANTIC_CATEGORIES) }]
          : [];
      }),
    },
  };
}

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

/** "18/20 (90.0%, 95% CI 69.9 to 97.2%)": counts first, never a bare percentage. */
export function cell(r: Rate): string {
  if (r.rate === null || r.ci === null) return "n/a (0 cases)";
  return `${r.k}/${r.n} (${pct(r.rate)}, 95% CI ${(r.ci[0] * 100).toFixed(1)} to ${(r.ci[1] * 100).toFixed(1)}%)`;
}
const count = (r: Rate) => `${r.k}/${r.n}`;
const ms = (x: number | null) => (x === null ? "n/a" : `${x} ms`);

function table(head: string[], rows: string[][]): string {
  const line = (cols: string[]) => `| ${cols.join(" | ")} |`;
  return [line(head), line(head.map(() => "---")), ...rows.map(line)].join("\n");
}

const sign = (x: number | null) =>
  x === null ? "n/a" : `${x >= 0 ? "+" : ""}${x.toFixed(1)} points`;

/** Honest-reporting rules of docs/08 section 5.5, applied mechanically to the data. */
export function renderReport(run: RunFile): string {
  const cfgs = run.config.configs;
  const S = run.results.configs;
  const out: string[] = [];

  out.push(`# Benchmark report: ${run.run_id}`, "");
  out.push(
    `Synthetic cases generated by us from seed ${run.config.seed} (generator v${run.config.generator_version}): ` +
      `${run.config.headline_cases} headline cases plus ${run.config.controls} paired controls. ` +
      `Ground truth is set by construction, so these numbers have limited external validity.`,
    "",
  );
  out.push(
    table(
      ["Item", "Value"],
      [
        ["Judges configured", String(run.config.judges)],
        [
          "Models",
          run.config.models.length
            ? run.config.models
                .map((m) => `${m.role}: ${m.name} (${m.version.slice(0, 12)})`)
                .join("; ")
            : "none (rules-only run)",
        ],
        ["Prompt hash", run.config.prompt_hash ?? "n/a"],
        ["Settings hash", run.config.settings_hash ?? "n/a"],
        ["Configurations", cfgs.map((c) => `${c}: ${DESCRIPTION[c]}`).join("<br>")],
      ],
    ),
    "",
  );

  const row = (label: string, f: (s: Summary) => string) => [label, ...cfgs.map((c) => f(S[c]!))];
  out.push("## Headline: safety first", "");
  out.push(
    table(
      ["Metric", ...cfgs],
      [
        row("False-refund rate (merchant wrongly refunded)", (s) => cell(s.false_refund_rate)),
        row("Injection resistance (verdict equals paired control)", (s) =>
          cell(s.injection_resistance),
        ),
        row("Overall accuracy (abstentions count as wrong)", (s) => cell(s.overall_accuracy)),
        row("Accuracy among decided", (s) => cell(s.accuracy_among_decided)),
        row("Abstain rate (needs_human_review)", (s) => cell(s.abstain_rate)),
        row("Missed-refund rate", (s) => cell(s.missed_refund_rate)),
        row("Citation validity (cases that reached a judge)", (s) => cell(s.citation_validity)),
        row(
          "Latency p50 / p95 (uncached cases)",
          (s) => `${ms(s.latency_ms.p50)} / ${ms(s.latency_ms.p95)} (n=${s.latency_ms.n})`,
        ),
        row("Mean model calls per case", (s) =>
          s.mean_model_calls === null ? "n/a" : s.mean_model_calls.toFixed(2),
        ),
      ],
    ),
    "",
  );

  out.push("## AI lift", "");
  if (run.results.lift.length === 0) {
    out.push(
      "No AI configuration was run together with a rules-only baseline, so there is no lift to report.",
      "",
    );
  } else {
    out.push(
      table(
        ["AI config vs baseline", "Overall", "Semantic categories only"],
        run.results.lift.map((l) => [
          `${l.ai} vs ${l.baseline}`,
          `${sign(l.overall.points)} (${count(l.overall.ai as Rate)} vs ${count(l.overall.baseline as Rate)})`,
          `${sign(l.semantic.points)} (${count(l.semantic.ai as Rate)} vs ${count(l.semantic.baseline as Rate)})`,
        ]),
      ),
      "",
    );
    for (const l of run.results.lift) {
      const verdict =
        l.overall.points === null
          ? "could not be computed"
          : l.overall.points > 0
            ? "improved overall accuracy"
            : l.overall.points === 0
              ? "did not change overall accuracy"
              : "reduced overall accuracy";
      out.push(`- ${l.ai} ${verdict} compared with ${l.baseline}: ${sign(l.overall.points)}.`);
    }
    out.push("");
  }

  const cats = Object.keys(S[cfgs[0]!]?.per_category ?? {});
  out.push("## Per-category accuracy", "");
  out.push(
    table(
      ["Category", "Truth", ...cfgs],
      cats.map((cat) => [
        cat,
        S[cfgs[0]!]!.per_category[cat]!.truth,
        ...cfgs.map((c) => count(S[c]!.per_category[cat] ?? { k: 0, n: 0, rate: null, ci: null })),
      ]),
    ),
    "",
  );

  out.push("## Confusion matrices (rows: truth, columns: predicted)", "");
  const labels: Label[] = ["REFUND", "RELEASE", "REVIEW"];
  for (const c of cfgs) {
    out.push(`### ${c}`, "");
    out.push(
      table(
        ["truth \\ predicted", ...labels],
        labels.map((t) => [t, ...labels.map((p) => String(S[c]!.confusion[t][p]))]),
      ),
      "",
    );
  }

  out.push(
    "## Limits",
    "",
    "- Every category is reported above, including the weak ones. Abstentions are shown separately and never hidden inside accuracy.",
    "- The cases are synthetic and generated by the same team that built the system; rates with small n carry wide intervals (shown above).",
    "- The false-refund rate and injection resistance are the headline safety numbers.",
    "- Latency is measured only on cases that made no cache hit.",
    "",
  );
  return out.join("\n");
}
