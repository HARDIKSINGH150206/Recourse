import { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { BenchChart } from "../components/BenchChart";
import { BenchTable } from "../components/BenchTable";
import { ApiError, request } from "../lib/api";
import { CONFIG_IDS, LABELS, fmtRate, type BenchRun, type ConfigId } from "../lib/bench";
import { config } from "../lib/config";
import { Hash } from "../components/Copy";

const DESCRIPTION: Record<ConfigId, string> = {
  A1: "rules only; abstains when no rule is decisive",
  A2: "rules only; defaults to release",
  B: "rules + extractor + one judge",
  C: "full system: extractor + judge quorum + citation check",
};

export function BenchPage() {
  const q = useQuery({
    queryKey: ["bench-latest"],
    queryFn: () => request<BenchRun>(config.apiUrl, "/bench/latest"),
  });
  const [selected, setSelected] = useState<ConfigId | null>(null);

  if (q.isPending) return <p className="muted">Loading…</p>;
  if (q.error instanceof ApiError && q.error.status === 404) {
    return (
      <>
        <h1>Benchmark</h1>
        <p>
          No benchmark run is stored yet. Run <code>pnpm bench</code>, then{" "}
          <code>pnpm bench:ingest bench/results/&lt;run&gt;/summary.json</code>.
        </p>
      </>
    );
  }
  if (q.error) return <p className="bad">Cannot load the benchmark from the API.</p>;

  const run = q.data;
  const present = CONFIG_IDS.filter((id) => run.results.configs[id]);
  const active = selected && run.results.configs[selected] ? selected : present[0];
  const summary = active ? run.results.configs[active] : undefined;
  const categories = [
    ...new Set(present.flatMap((id) => Object.keys(run.results.configs[id]!.per_category))),
  ].sort();

  return (
    <>
      <h1>Benchmark</h1>
      <p className="muted">
        Run {run.run_id} · seed {run.config.seed ?? "?"} · {run.config.headline_cases ?? "?"}{" "}
        headline cases · {new Date(run.created_at * 1000).toLocaleString()}. The cases are synthetic
        and generated by us, so they say less about the real world than a held-out set would.
      </p>
      {run.config.models && run.config.models.length > 0 && (
        <p className="muted">
          Models: {run.config.models.map((m) => `${m.role} ${m.name}`).join(", ")}
          {run.config.prompt_hash && (
            <>
              {" "}
              · prompt <Hash value={run.config.prompt_hash} />
            </>
          )}
        </p>
      )}

      <h2>Accuracy</h2>
      <BenchChart run={run} />
      <h2>Results by configuration</h2>
      <ul>
        {present.map((id) => (
          <li key={id}>
            <strong>{id}</strong>: {DESCRIPTION[id]}
          </li>
        ))}
      </ul>
      <BenchTable run={run} />

      {run.results.lift && run.results.lift.length > 0 && (
        <>
          <h2>AI lift</h2>
          <p className="muted">
            Accuracy of the AI configuration minus the rules-only baseline, in percentage points.
            Small or negative values are reported as they are.
          </p>
          <table>
            <thead>
              <tr>
                <th>Comparison</th>
                <th>Overall</th>
                <th>Semantic categories</th>
              </tr>
            </thead>
            <tbody>
              {run.results.lift.map((l) => (
                <tr key={`${l.ai}-${l.baseline}`}>
                  <th>
                    {l.ai} vs {l.baseline}
                  </th>
                  <td>{l.overall?.points?.toFixed(1) ?? "n/a"}</td>
                  <td>{l.semantic?.points?.toFixed(1) ?? "n/a"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </>
      )}

      <h2>By category</h2>
      <table>
        <thead>
          <tr>
            <th>Category</th>
            <th>Truth</th>
            {present.map((id) => (
              <th key={id}>{id}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {categories.map((c) => {
            const truth = present
              .map((id) => run.results.configs[id]!.per_category[c]?.truth)
              .find(Boolean);
            return (
              <tr key={c}>
                <th>{c}</th>
                <td>{truth ?? ""}</td>
                {present.map((id) => (
                  <td key={id}>{fmtRate(run.results.configs[id]!.per_category[c])}</td>
                ))}
              </tr>
            );
          })}
        </tbody>
      </table>

      {summary && active && (
        <>
          <h2>Confusion matrix</h2>
          <label htmlFor="cfg">Configuration</label>
          <select
            id="cfg"
            value={active}
            onChange={(e) => setSelected(e.target.value as ConfigId)}
            style={{ width: "auto" }}
          >
            {present.map((id) => (
              <option key={id} value={id}>
                {id}
              </option>
            ))}
          </select>
          <table>
            <caption className="muted" style={{ textAlign: "left" }}>
              Rows are the truth, columns the prediction (headline cases only).
            </caption>
            <thead>
              <tr>
                <th>Truth \ predicted</th>
                {LABELS.map((l) => (
                  <th key={l}>{l}</th>
                ))}
              </tr>
            </thead>
            <tbody>
              {LABELS.map((t) => (
                <tr key={t}>
                  <th>{t}</th>
                  {LABELS.map((p) => (
                    <td key={p}>{summary.confusion[t][p]}</td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </>
      )}
    </>
  );
}
