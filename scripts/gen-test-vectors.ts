// Writes packages/shared/test/vectors.json: fixed keys, mandate, entries, tree head, receipt,
// bundle and the expected VerificationReport (docs/03 section 13). Deterministic.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { verifyBundle } from "../packages/shared/src/index.js";
import {
  CHAIN_ID,
  ESCROW,
  KEYS,
  MANDATE_ID,
  buildFixture,
  mandate,
  terms,
} from "../packages/shared/test/fixture.js";

const fx = await buildFixture();
const report = await verifyBundle(fx.bundle, {
  batchEntries: fx.batch,
  blobs: { [fx.bundle.receipt!.responseHash]: fx.blob },
  disputeTs: 1_767_200_100,
});

const out = {
  note: "Generated by scripts/gen-test-vectors.ts. Test keys only (anvil dev keys).",
  keys: KEYS,
  chain_id: CHAIN_ID,
  escrow: ESCROW,
  terms,
  mandate,
  mandate_id: MANDATE_ID,
  entries: fx.batch,
  bundle: fx.bundle,
  expected_report: report,
};

const path = fileURLToPath(new URL("../packages/shared/test/vectors.json", import.meta.url));
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${path}`);
